let currentLanguage = 'de';
export const getLanguage = () => currentLanguage;
export const t = (key, values = {}) => {
    const text = translations[currentLanguage]?.[key] ?? translations.de[key] ?? key;
    return text.replace(/\{(\w+)\}/g, (match, name) => String(values[name] ?? match));
};

export const setLanguage = (language, persist = true) => {
    currentLanguage = Object.hasOwn(translations, language) ? language : 'de';
    document.documentElement.lang = currentLanguage;
    document.title = t('page-title');
    document.querySelector('meta[name="description"]').content = t('page-description');
    document.querySelector('meta[property="og:title"]').content = t('page-title');
    document.querySelector('meta[property="og:description"]').content = t('page-description');
    document.querySelectorAll('[data-i18n]').forEach(element => {
        element.textContent = t(element.dataset.i18n);
    });
    for (const [dataKey, attribute] of [['i18nAriaLabel', 'aria-label'], ['i18nAlt', 'alt'], ['i18nTitle', 'title']]) {
        document.querySelectorAll('[data-' + dataKey.replace(/[A-Z]/g, char => '-' + char.toLowerCase()) + ']').forEach(element => {
            element.setAttribute(attribute, t(element.dataset[dataKey]));
        });
    }
    document.querySelectorAll('[data-product-key]').forEach(element => {
        element.dataset.title = t(element.dataset.productKey);
    });
    const button = document.querySelector('#selected-lang');
    button.textContent = currentLanguage.toUpperCase();
    button.className = 'selected-lang ' + currentLanguage;
    if (persist) {
        try { localStorage.setItem('lang', currentLanguage); } catch { /* Language still works without storage. */ }
    }
    document.dispatchEvent(new CustomEvent('languagechange'));
};

export const initLanguage = () => {
    let saved;
    try { saved = localStorage.getItem('lang'); } catch { /* Storage may be unavailable. */ }
    const browserLanguage = (navigator.language || 'de').split('-')[0].toLowerCase();
    setLanguage(saved && Object.hasOwn(translations, saved) ? saved : browserLanguage, false);
};
